def inventory_delta(present, table=None):
    """THE one unlisted/missing rule — (unlisted, missing).

    P-O6 (#827, SEQ 866): extracted so the attack tests can exercise THIS
    function instead of re-implementing it. A test that copies the rule
    proves the copy: weaken main()'s real refusal and a copied check stays
    green while the boundary it claims to guard is gone. One owner, both
    callers.
    """
    table = PROVENANCE if table is None else table
    return ([f for f in present if f not in table],
            sorted(f for f in table if f not in present))


def main():
    present = sorted(f for f in os.listdir(_HERE)
                     if os.path.isfile(os.path.join(_HERE, f))
                     and f != os.path.basename(OUT))
    unlisted, _missing_later = inventory_delta(present)
    if unlisted:
        raise SystemExit(
            f"{len(unlisted)} receipt file(s) have no command in this index: "
            f"{unlisted}. Add them — a receipt nobody can reproduce is not a "
            f"receipt.")
    # A REQUIRED RECEIPT THAT IS NOT THERE IS A FAILURE, not a footnote. The
    # first version listed it under a comment and still returned success, so an
    # index could describe a set of receipts that does not exist.
    _unlisted_again, missing = inventory_delta(present)
    if missing:
        raise SystemExit(
            f"{len(missing)} receipt(s) named by this index are NOT on disk: "
            f"{missing}. Produce them, or remove them from the table — an "
            f"index for absent receipts is not an index.")

    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=_REPO, check=True,
                          capture_output=True, text=True).stdout.strip()
    if len(head) != 40 or not all(c in "0123456789abcdef" for c in head):
        raise SystemExit(f"git rev-parse HEAD returned {head!r}, not a commit")
    lines = [
        "# #827 receipt index — the PROVENANCE OR REPLAY COMMAND for each",
        "# receipt, and its SHA-256. Both are needed: a hash says a file did not",
        "# change, it does not say where the file came from.",
        "#",
        "# THE FIELD IS NOT 'command', and that wording was the defect. Some of",
        "# these receipts are REPLAY COMMANDS — run it again and you get the",
        "# file. Others are WRITTEN RECORDS (a freeze snapshot, a law record, a",
        "# hand-classified census) which no command reproduces, and printing an",
        "# invented command beside them claimed a reproducibility that does not",
        "# exist. Each line now says which kind it is.",
        "#",
        "# GENERATED by make_index.py — the hashes were transcribed by hand",
        "# until #827 round 5, which is precisely how an index drifts.",
        f"# baseline commit: {head}",
        "",
    ]
    for name in present:
        with open(os.path.join(_HERE, name), "rb") as fh:
            digest = hashlib.sha256(fh.read()).hexdigest()
        lines += [name, f"    provenance: {PROVENANCE[name]}",
                  f"    sha256    : {digest}", ""]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines))
    print(f"indexed {len(present)} receipts")
    print(f"wrote {os.path.basename(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
